#!/usr/bin/env node
/* Auto-merge's design check (.github/workflows/auto-merge.yml, the block between "DESIGN-CHECK START" and "DESIGN-CHECK END")
   run in Node against fixtures, no network: a PR that commits review shots must wait for the Design Lead's DESIGN OK on its
   head (owner, typed 2026-10-18 7:13 PM ET; 0.7 P6 #378 merged before its shots were checked). < 1 s. */
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const yml = readFileSync(join(ROOT, '.github', 'workflows', 'auto-merge.yml'), 'utf8');
let n = 0, fail = 0;
const check = (ok, what) => { n++; if (!ok) fail++; console.log(`${ok ? 'ok  ' : 'FAIL'} ${what}`); };

const m = yml.match(/\/\/ DESIGN-CHECK START[^\n]*\n([\s\S]*?)\n\s*\/\/ DESIGN-CHECK END/);
check(!!m, 'auto-merge.yml has the DESIGN-CHECK block');
if (!m) { console.log('AUTOMERGE CHECKS FAILED'); process.exit(1); }
const logs = [];
const designBlocker = new Function('owner', 'core', m[1] + '\nreturn designBlocker;')('HackTheMeatball', { info: (s) => logs.push(s) });

const SHA = 'abc1234def5678';
const HEAD = Date.parse('2026-10-18T20:00:00Z');
const at = (min) => new Date(HEAD + min * 60000).toISOString();
const c = (login, body, min) => ({ user: { login }, body, updated_at: at(min) });
const SHOTS = ['src/cards/sync.js', 'docs/reviews/0.7-p7-shots/scrapbook.json', 'docs/reviews/0.7-p7-shots/j1-390-after.png'];
const REVIEW = c('claude[bot]', 'Review of abc1234\nNothing blocking.\nVERDICT: APPROVE', 5);

check(designBlocker(['src/main.js', 'docs/design/mockups/0.7-sync/a1-390.png'], [REVIEW], SHA, HEAD) === '', 'no review shots -> no wait');
check(/wait on DESIGN OK/.test(designBlocker(SHOTS, [REVIEW], SHA, HEAD)), 'shots, no DESIGN OK -> waits');
check(designBlocker(SHOTS, [REVIEW, c('claude[bot]', 'DESIGN OK on abc1234: shots match the mockup.', 9)], SHA, HEAD) === '', 'DESIGN OK from claude[bot] naming the head -> merges');
check(designBlocker(SHOTS, [c('HackTheMeatball', 'DESIGN OK abc1234', 9)], SHA, HEAD) === '', 'DESIGN OK from the repo owner -> merges');
check(/by HackTheMeatball, typed/.test(logs.at(-1)), 'owner-account DESIGN OK without the footer is logged as typed');
logs.length = 0;
designBlocker(SHOTS, [c('HackTheMeatball', 'DESIGN OK on abc1234.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_', 9)], SHA, HEAD);
check(/from a Claude session/.test(logs.at(-1) || ''), 'DESIGN OK with the Claude Code footer is logged as a session');
check(/does not cover the head/.test(designBlocker(SHOTS, [c('claude[bot]', 'DESIGN OK on 9999999', 9)], SHA, HEAD)), 'DESIGN OK naming another commit -> waits');
check(/does not cover the head/.test(designBlocker(SHOTS, [c('claude[bot]', 'DESIGN OK on abc1234', -3)], SHA, HEAD)), 'DESIGN OK older than the head commit -> waits');
check(/asked for changes/.test(designBlocker(SHOTS, [c('claude[bot]', 'DESIGN OK abc1234', 6), c('claude[bot]', 'DESIGN CHANGES abc1234: the code is cut off at 390.', 8)], SHA, HEAD)), 'later DESIGN CHANGES wins');
check(designBlocker(SHOTS, [c('claude[bot]', 'DESIGN CHANGES abc1234', 6), c('claude[bot]', 'DESIGN OK abc1234', 8)], SHA, HEAD) === '', 'later DESIGN OK wins');
check(/wait on DESIGN OK/.test(designBlocker(SHOTS, [c('someone-else', 'DESIGN OK abc1234', 9)], SHA, HEAD)), 'DESIGN OK from another account -> ignored, waits');
check(/wait on DESIGN OK/.test(designBlocker(SHOTS, [c('claude[bot]', 'Looks fine. A DESIGN OK will follow for abc1234.', 9)], SHA, HEAD)), '"DESIGN OK" not at a line start -> ignored, waits');

// The merge loop runs the check after the review checks and before it merges.
const loop = yml.slice(yml.indexOf('for (const pr of prs)'), yml.indexOf('github.rest.pulls.merge('));
check(/const design = designBlocker\(files, comments, sha, headAt\);\s*\n\s*if \(design\) \{.*continue; \}/.test(loop), 'merge loop: designBlocker runs and skips before a PR is merged');

console.log(`\n${n - fail}/${n} auto-merge checks passed`);
console.log(fail ? 'AUTOMERGE CHECKS FAILED' : 'AUTOMERGE CHECKS PASSED');
process.exit(fail ? 1 : 0);
